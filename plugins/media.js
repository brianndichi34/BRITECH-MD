const { downloadMediaMessage } = require('@whiskeysockets/baileys');
const QRCode = require('qrcode');
const sharp = require('sharp');

const MAX_INPUT_BYTES = 8 * 1024 * 1024;
const MAX_OUTPUT_BYTES = 1024 * 1024;
const logger = { trace() {}, debug() {}, info() {}, warn() {}, error() {} };

function contextInfo(message) {
  for (const value of Object.values(message?.message || {})) {
    if (value && typeof value === 'object' && value.contextInfo) return value.contextInfo;
  }
  return {};
}

function quotedMessage(message, chat) {
  const info = contextInfo(message);
  if (!info.quotedMessage || !info.stanzaId) return null;
  return {
    key: {
      remoteJid: chat,
      id: info.stanzaId,
      participant: info.participant,
      fromMe: Boolean(info.fromMe)
    },
    message: info.quotedMessage
  };
}

function mediaNode(message) {
  for (const [key, value] of Object.entries(message?.message || {})) {
    if (/^(image|sticker|video)Message$/.test(key) && value && typeof value === 'object') return { type: key, node: value };
  }
  return null;
}

async function readMedia(message, chat, downloader = downloadMediaMessage) {
  const target = quotedMessage(message, chat) || message;
  const media = mediaNode(target);
  if (!media) throw new Error('Reply to an image or sticker, or send an image with the command as its caption.');
  if (media.type === 'videoMessage') throw new Error('Video-to-sticker is not enabled because it requires a system FFmpeg binary. Send a still image instead.');
  const size = Number(media.node.fileLength || 0);
  if (size > MAX_INPUT_BYTES) throw new Error('That image is over the 8 MB processing limit.');
  const buffer = await downloader(target, 'buffer', {}, { logger });
  if (!Buffer.isBuffer(buffer) || !buffer.length) throw new Error('WhatsApp did not provide the image data. Try sending it again.');
  if (buffer.length > MAX_INPUT_BYTES) throw new Error('That image is over the 8 MB processing limit.');
  return { buffer, type: media.type };
}

async function createStickerBuffer(buffer) {
  let output = await sharp(buffer, { limitInputPixels: 16000000 })
    .rotate()
    .resize(512, 512, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 78, effort: 5 })
    .toBuffer();
  if (output.length > MAX_OUTPUT_BYTES) {
    output = await sharp(buffer, { limitInputPixels: 16000000 })
      .rotate()
      .resize(512, 512, { fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 55, effort: 6 })
      .toBuffer();
  }
  if (output.length > MAX_OUTPUT_BYTES) throw new Error('The converted sticker is still over 1 MB. Try a smaller image.');
  return output;
}

async function stickerToPng(buffer) {
  const image = await sharp(buffer, { limitInputPixels: 16000000 }).png({ compressionLevel: 9 }).toBuffer();
  if (image.length > MAX_OUTPUT_BYTES * 4) throw new Error('The converted PNG is too large to send.');
  return image;
}

async function createQrImage(text) {
  if (!text) throw new Error('QR text is required.');
  if (Buffer.byteLength(text, 'utf8') > 1500) throw new Error('QR text is limited to 1,500 bytes.');
  return QRCode.toBuffer(text, { type: 'png', errorCorrectionLevel: 'M', margin: 2, scale: 6 });
}

module.exports = {
  name: 'local-media',
  category: 'MEDIA',
  commands: {
    sticker: 'Turn a replied image or image caption into a WhatsApp sticker',
    toimg: 'Convert a replied sticker into a PNG image',
    qr: 'Generate a QR code image from text'
  },
  createStickerBuffer,
  stickerToPng,
  createQrImage,
  readMedia,
  async handle(command, ctx) {
    if (command === 'qr') {
      if (!ctx.query) return ctx.reply(`Usage: ${ctx.config.prefix}qr text or URL`);
      const image = await createQrImage(ctx.query);
      return ctx.sock.sendMessage(ctx.chat, { image, caption: 'QR code generated by BRITECH MD.' }, { quoted: ctx.msg });
    }

    const { buffer, type } = await readMedia(ctx.msg, ctx.chat, ctx.downloadMediaMessage || downloadMediaMessage);
    if (command === 'sticker') {
      if (type === 'stickerMessage') return ctx.reply('That is already a sticker. Reply to an image instead.');
      const output = await createStickerBuffer(buffer);
      return ctx.sock.sendMessage(ctx.chat, { sticker: output }, { quoted: ctx.msg });
    }

    if (command === 'toimg') {
      if (type !== 'stickerMessage') return ctx.reply('Reply to a sticker with .toimg.');
      const image = await stickerToPng(buffer);
      return ctx.sock.sendMessage(ctx.chat, { image, mimetype: 'image/png', caption: 'Converted from a WhatsApp sticker.' }, { quoted: ctx.msg });
    }
  }
};
